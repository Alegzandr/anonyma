"""MIME messages (eml): extraction and faithful re-serialisation.

Shared by the eml, msg (converted to eml), mbox and pst plugins.

Extraction (:func:`extract_mime`) parses the message with the ``compat32`` policy
and exposes:

* every header (RFC 2047 decoded, unfolded, 8-bit tolerant) as a HEADER segment,
  except the signature headers listed in :data:`DROPPED_HEADERS`;
* the unix ``From `` line, if any;
* every inline ``text/*`` part (charset and transfer encoding decoded), HTML
  parts through the shared HTML tokenizer;
* attachments, inline (``cid:``) images, ``data:`` images of HTML parts and
  attached messages (``message/rfc822``) as children.

The writer (:func:`write_mime`) re-parses the same source, walks the same tree and
serialises it again by hand: kept headers are copied verbatim unless one of their
characters is replaced (then re-encoded with RFC 2047 and folded); content headers
are regenerated (fresh boundaries, only structural parameters kept, anonymized
file names), bodies are re-encoded with their original charset and transfer
encoding (UTF-8 / quoted-printable fallbacks), preambles and epilogues dropped.

Headers dropped on output (documented choice): cryptographic signatures and opaque
blobs that can neither stay valid nor be anonymized, while their hashes and keys
fingerprint the original message or person (DKIM/ARC signatures, Autocrypt keys,
Google/Microsoft opaque tracking blobs, TNEF correlators). ``Authentication-Results``
and ``ARC-Authentication-Results`` carry structure and are kept, anonymized
through segments like ``Received``.
"""

