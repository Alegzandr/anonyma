@dataclass(slots=True)
class _Writing:
    document: Document
    plan: ReplacementPlan
    child_outputs: Mapping[str, ChildOutput]
    newline: str
    headers: dict[str, list[Segment]]
    bodies: dict[str, list[Segment]]
    issues: list[Issue] = field(default_factory=list)


def write_mime(
    data: bytes,
    document: Document,
    plan: ReplacementPlan,
    child_outputs: Mapping[str, ChildOutput],
) -> tuple[bytes, list[Issue]]:
    """Serialise the anonymized message. Children whose output is missing are
    omitted (the pipeline already reports them)."""
    message = parse_message(data)
    newline: str = document.properties.get("newline", detect_newline(data))
    headers: dict[str, list[Segment]] = {}
    bodies: dict[str, list[Segment]] = {}
    for segment in document.segments:
        if segment.id.startswith("p") and ":" in segment.id:
            path, rest = segment.id[1:].split(":", 1)
            target = headers if rest.startswith(HEADER) else bodies
            target.setdefault(path, []).append(segment)
    state = _Writing(document, plan, child_outputs, newline, headers, bodies)
    out = bytearray()
    unixfrom = message.get_unixfrom()
    if unixfrom:
        try:
            segment = document.segment(UNIXFROM_ID)
            line = plan.apply(segment)
        except KeyError:
            line = _decode_raw(unixfrom[5:])
        out += ("From " + line.replace("\r", " ").replace("\n", " ") + newline).encode("utf-8")
    rendered = _render_part(message, "0", state)
    if rendered is None:
        raise ValueError("message vide")
    out += rendered
    return bytes(out), state.issues


def _header_lines(part: Message, path: str, state: _Writing) -> list[str]:
    by_index = {int(s.locator[2]): s for s in state.headers.get(path, [])}
    lines: list[str] = []
    nl = state.newline
    for index, (name, value) in enumerate(part.items()):
        lname = name.lower()
        if lname in DROPPED_HEADERS or lname in STRUCTURAL_HEADERS:
            continue
        segment = by_index.get(index)
        if segment is not None and state.plan.for_segment(segment.id):
            new = state.plan.apply(segment)
            lines.append(fold_header(name, encode_header_text(new), nl))
        else:
            raw = str(value)
            raw = re.sub(r"\r?\n", nl, raw)
            lines.append(f"{name}: {raw.lstrip(' ')}{nl}" if raw else f"{name}:{nl}")
    return lines


def _quote_param(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _filename_params(key: str, name: str) -> str:
    if name.isascii():
        return f"{key}={_quote_param(name)}"
    from urllib.parse import quote

    return f"{key}*=utf-8''{quote(name, safe='')}"


def _content_type(ctype: str, params: Sequence[tuple[str, str]]) -> str:
    rendered = "".join(
        f"; {_filename_params(k, v) if k == 'name' else f'{k}={_quote_param(v)}'}"
        for k, v in params
    )
    return ctype + rendered


def _render_part(part: Message, path: str, state: _Writing) -> bytes | None:
    nl = state.newline
    ctype = part.get_content_type()
    maintype = part.get_content_maintype()
    if ctype in _SIGNATURE_TYPES:
        return None
    header_lines = _header_lines(part, path, state)
    kept_params = [
        (k, str(v))
        for k in _KEPT_TYPE_PARAMS
        if (v := _param(part, k)) is not None and k in _KEPT_TYPE_PARAMS
    ]

    if part.is_multipart() and maintype == "multipart":
        payload = part.get_payload()
        rendered = [
            r
            for i, sub in enumerate(payload if isinstance(payload, list) else [])
            if (r := _render_part(sub, f"{path}.{i}", state)) is not None
        ]
        if not rendered:
            return None
        boundary = f"=_anonyma_{uuid.uuid4().hex}"
        params = [*kept_params, ("boundary", boundary)]
        header_lines.append(fold_header("Content-Type", _content_type(ctype, params), nl))
        body = bytearray()
        for r in rendered:
            body += f"--{boundary}{nl}".encode("ascii") + r + nl.encode("ascii")
        body += f"--{boundary}--{nl}".encode("ascii")
        return "".join(header_lines).encode("utf-8", "surrogateescape") + nl.encode() + body

    if path in state.document.properties.get("mime_children", {}):
        return _render_child(part, path, header_lines, kept_params, state)

    if maintype == "text":
        return _render_text(part, path, header_lines, kept_params, state)
    return None  # leaf neither text nor child: nothing extracted, nothing written


def _render_text(
    part: Message,
    path: str,
    header_lines: list[str],
    kept_params: list[tuple[str, str]],
    state: _Writing,
) -> bytes:
    nl = state.newline
    text = _decode_text(part)
    segments = state.bodies.get(path, [])
    if part.get_content_subtype() == "html":
        source = HtmlSource(text)
        edits = plan_edits(source, segments, state.plan)
        values: dict[int, str] = {}
        for unit, child_id in (
            state.document.properties.get("mime_html_children", {}).get(path, {}).items()
        ):
            output = state.child_outputs.get(child_id)
            values[unit] = (
                ""
                if output is None or output.path is None
                else data_uri_value(mime_for(output.name), output.path.read_bytes())
            )
        new_text = source.rewrite(edits, values)
    else:
        new_text = _apply_chunks(text, segments, state.plan)
    charset = part.get_content_charset()
    codec = _codec(charset)
    try:
        body = new_text.encode(codec or "ascii")
    except UnicodeEncodeError:
        charset, body = "utf-8", new_text.encode("utf-8")
    params = list(kept_params)
    if charset:
        params.insert(0, ("charset", charset))
    cte = str(part.get("content-transfer-encoding", "")).strip().lower()
    encoded, cte = _encode_body(body, cte, nl)
    header_lines.append(
        fold_header("Content-Type", _content_type(part.get_content_type(), params), nl)
    )
    if cte:
        header_lines.append(f"Content-Transfer-Encoding: {cte}{nl}")
    disposition = _disposition(part)
    if disposition:
        header_lines.append(f"Content-Disposition: {disposition}{nl}")
    return "".join(header_lines).encode("utf-8", "surrogateescape") + nl.encode() + encoded


def _apply_chunks(text: str, segments: Sequence[Segment], plan: ReplacementPlan) -> str:
    """Rebuild a chunked text body (chunks cover the text; blank chunks have no
    segment and are copied as-is)."""
    by_offset = {int(s.locator[2]): s for s in segments if s.locator[0] == "text"}
    out: list[str] = []
    for offset, chunk in chunk_text(text):
        segment = by_offset.get(offset)
        out.append(plan.apply(segment) if segment is not None else chunk)
    return "".join(out)


def _encode_body(body: bytes, cte: str, nl: str) -> tuple[bytes, str]:
    if cte == "base64":
        return _base64_lines(body, nl), "base64"
    if cte == "quoted-printable" or (not body.isascii() and cte not in ("8bit", "binary")):
        text = email.quoprimime.body_encode(body.decode("latin-1"), maxlinelen=76, eol=nl)
        if not text.endswith(nl):
            text += nl
        return text.encode("ascii"), "quoted-printable"
    normalized = re.sub(rb"\r?\n", nl.encode(), body)
    if not normalized.endswith(nl.encode()):
        normalized += nl.encode()
    return normalized, ("8bit" if cte == "binary" else cte)


def _base64_lines(data: bytes, nl: str) -> bytes:
    encoded = base64.b64encode(data)
    lines = [encoded[i : i + 76] for i in range(0, len(encoded), 76)]
    return b"".join(line + nl.encode() for line in lines)


def _render_child(
    part: Message,
    path: str,
    header_lines: list[str],
    kept_params: list[tuple[str, str]],
    state: _Writing,
) -> bytes | None:
    nl = state.newline
    child_id = state.document.properties["mime_children"][path]
    output = state.child_outputs.get(child_id)
    if output is None or output.path is None:
        return None
    data = output.path.read_bytes()
    name = PurePosixPath(output.name.replace("\\", "/")).name
    original_name = attachment_name(part)
    ctype = part.get_content_type()
    out_suffix = PurePosixPath(name).suffix.lower()
    if out_suffix == ".eml":
        ctype = "message/rfc822"
    elif part.get_content_maintype() == "message" or (
        original_name is not None and PurePosixPath(original_name).suffix.lower() != out_suffix
    ):
        ctype = mime_for(name)
    type_params: list[tuple[str, str]] = []
    if original_name is not None:
        type_params.append(("name", name))
    header_lines.append(fold_header("Content-Type", _content_type(ctype, type_params), nl))
    if ctype == "message/rfc822":
        body = re.sub(rb"\r?\n", nl.encode(), data)
        header_lines.append(
            f"Content-Transfer-Encoding: {'7bit' if body.isascii() else '8bit'}{nl}"
        )
    else:
        body = _base64_lines(data, nl)
        header_lines.append(f"Content-Transfer-Encoding: base64{nl}")
    disposition = _disposition(part) or ("attachment" if original_name else "")
    if disposition or original_name:
        value = disposition or "attachment"
        if original_name is not None:
            value += "; " + _filename_params("filename", name)
        header_lines.append(fold_header("Content-Disposition", value, nl))
    return "".join(header_lines).encode("utf-8", "surrogateescape") + nl.encode() + body


# ---------------------------------------------------------------------------
# Building messages (msg / pst conversion)
# ---------------------------------------------------------------------------


@dataclass(slots=True)
class BuiltAttachment:
    name: str
    data: bytes
    content_type: str = "application/octet-stream"
    content_id: str | None = None
    inline: bool = False


def build_eml(
    headers: Sequence[tuple[str, str]],
    plain: str | None,
    html_body: str | None,
    attachments: Sequence[BuiltAttachment] = (),
) -> bytes:
    """Build an RFC 5322 message (CRLF, UTF-8, quoted-printable bodies)."""
    nl = "\r\n"

    def leaf(ctype: str, body: bytes, extra: Sequence[str] = (), qp: bool = True) -> bytes:
        lines = [fold_header("Content-Type", ctype, nl), *extra]
        if qp:
            encoded, cte = _encode_body(body, "quoted-printable", nl)
        else:
            encoded, cte = _base64_lines(body, nl), "base64"
        lines.append(f"Content-Transfer-Encoding: {cte}{nl}")
        return "".join(lines).encode("utf-8") + nl.encode() + encoded

    def multipart(subtype: str, parts: Sequence[bytes]) -> bytes:
        boundary = f"=_anonyma_{uuid.uuid4().hex}"
        out = bytearray(
            fold_header("Content-Type", f'multipart/{subtype}; boundary="{boundary}"', nl).encode()
        )
        out += nl.encode()
        for p in parts:
            out += f"--{boundary}{nl}".encode() + p + nl.encode()
        out += f"--{boundary}--{nl}".encode()
        return bytes(out)

    bodies: list[bytes] = []
    if plain is not None:
        bodies.append(leaf("text/plain; charset=utf-8", plain.encode("utf-8")))
    if html_body is not None:
        bodies.append(leaf("text/html; charset=utf-8", html_body.encode("utf-8")))
    if not bodies:
        bodies.append(leaf("text/plain; charset=utf-8", b""))
    body = bodies[0] if len(bodies) == 1 else multipart("alternative", bodies)
    if attachments:
        parts = [body]
        for att in attachments:
            extra = []
            if att.content_id:
                extra.append(fold_header("Content-ID", f"<{att.content_id.strip('<>')}>", nl))
            disposition = "inline" if att.inline else "attachment"
            extra.append(
                fold_header(
                    "Content-Disposition",
                    f"{disposition}; {_filename_params('filename', att.name)}",
                    nl,
                )
            )
            if att.content_type == "message/rfc822":
                lines = [fold_header("Content-Type", "message/rfc822", nl), *extra]
                payload = re.sub(rb"\r?\n", b"\r\n", att.data)
                lines.append(f"Content-Transfer-Encoding: 8bit{nl}")
                parts.append("".join(lines).encode("utf-8") + nl.encode() + payload)
            else:
                ctype = _content_type(att.content_type, [("name", att.name)])
                parts.append(leaf(ctype, att.data, extra, qp=False))
        body = multipart("mixed", parts)
    head = "".join(
        fold_header(name, encode_header_text(value), nl)
        for name, value in headers
        if value is not None and str(value).strip()
    )
    head += f"MIME-Version: 1.0{nl}"
    return head.encode("utf-8") + body


def reraise_fatal(exc: BaseException) -> None:
    """Re-raise exceptions that must cross plugin ``except`` clauses."""
    if isinstance(exc, (ArchiveBombError, CancelledError)):
        raise exc


