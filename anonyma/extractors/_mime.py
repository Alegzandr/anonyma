_ENCODED_WORD = re.compile(r"=\?([^?\s]+)\?([QqBb])\?([^?\s]*)\?=")
_FOLD = re.compile(r"\r?\n(?=[ \t])")

HEADER = "h"
BODY = "b"


# ---------------------------------------------------------------------------
# Header decoding / encoding
# ---------------------------------------------------------------------------


def _codec(charset: str | None) -> str | None:
    if not charset:
        return None
    name = charset.split("*", 1)[0].strip().strip('"').lower()
    try:
        return codecs.lookup(name).name
    except LookupError:
        return None


def _decode_raw(raw: str) -> str:
    """Undo ``surrogateescape`` of 8-bit header bytes (UTF-8, else cp1252)."""
    if not any("\udc80" <= c <= "\udcff" for c in raw):
        return raw
    data = raw.encode("ascii", "surrogateescape")
    return decode_bytes(data)[0]


def _decode_word_bytes(encoding: str, payload: str) -> bytes:
    if encoding in "Bb":
        payload = payload + "=" * (-len(payload) % 4)
        try:
            return base64.b64decode(payload)
        except (binascii.Error, ValueError):
            return payload.encode("ascii", "replace")
    data = payload.replace("_", " ").encode("ascii", "replace")
    return re.sub(rb"=([0-9A-Fa-f]{2})", lambda m: bytes([int(m.group(1), 16)]), data)


def decode_header_value(raw: str) -> str:
    """Unfold, decode 8-bit bytes and RFC 2047 encoded words.

    Whitespace between two encoded words is dropped (RFC 2047 §6.2); adjacent words
    of the same charset are decoded together so that split multibyte characters
    survive.
    """
    text = _decode_raw(_FOLD.sub("", raw)).strip("\r\n")
    if "=?" not in text:
        return text
    out: list[str] = []
    pending: list[bytes] = []
    pending_charset: str | None = None
    cursor = 0

    def flush() -> None:
        nonlocal pending_charset
        if pending:
            data = b"".join(pending)
            codec = _codec(pending_charset)
            try:
                out.append(data.decode(codec) if codec else decode_bytes(data)[0])
            except UnicodeDecodeError:
                out.append(decode_bytes(data)[0])
            pending.clear()
        pending_charset = None

    for match in _ENCODED_WORD.finditer(text):
        between = text[cursor : match.start()]
        if between and (not pending or between.strip()):
            flush()
            out.append(between)
        charset = match.group(1)
        if pending and _codec(charset) != _codec(pending_charset):
            flush()
        pending_charset = charset
        pending.append(_decode_word_bytes(match.group(2), match.group(3)))
        cursor = match.end()
    flush()
    out.append(text[cursor:])
    return "".join(out)


_TOKENS = re.compile(
    r'"(?:[^"\\]|\\.)*"?'  # quoted string
    r"|<[^>]*>?"  # angle address
    r"|\((?:[^()\\]|\\.)*\)?"  # comment (not nested)
    r"|[,;]"  # list separators
    r"|\s+"
    r'|[^\s",;<(]+'
)
_MAX_WORD_BYTES = 45


def _encoded_words(text: str) -> list[str]:
    """RFC 2047 ``B`` encoded words (each <= 75 chars), split on char boundaries."""
    words: list[str] = []
    chunk = ""
    for ch in text:
        if len((chunk + ch).encode("utf-8")) > _MAX_WORD_BYTES:
            words.append(chunk)
            chunk = ""
        chunk += ch
    if chunk:
        words.append(chunk)
    return [f"=?utf-8?b?{base64.b64encode(w.encode('utf-8')).decode('ascii')}?=" for w in words]


def _encode_phrase(text: str) -> str:
    return " ".join(_encoded_words(text))


def encode_header_text(text: str) -> str:
    """Encode a decoded header value: runs of words containing non-ASCII characters
    become encoded words; addresses (``<...>``) and ASCII parts stay readable."""
    text = text.replace("\r", " ").replace("\n", " ")
    if text.isascii():
        return text
    tokens = _TOKENS.findall(text)
    out: list[str] = []
    run: list[str] = []

    def flush_run() -> None:
        if not run:
            return
        joined = "".join(run)
        stripped = joined.strip()
        if stripped.isascii():
            out.append(joined)
        else:
            lead = joined[: len(joined) - len(joined.lstrip())]
            trail = joined[len(joined.rstrip()) :]
            plain = "".join(
                _unquote(t) if t.startswith('"') else t for t in _TOKENS.findall(stripped)
            )
            out.append(lead + _encode_phrase(plain) + trail)
        run.clear()

    for token in tokens:
        if token.startswith("<") or token in (",", ";"):
            flush_run()
            out.append(token)
        elif token.startswith("(") and not token.isascii():
            flush_run()
            out.append("(" + _encode_phrase(token.strip("()")) + ")")
        else:
            run.append(token)
    flush_run()
    return "".join(out)


def _unquote(token: str) -> str:
    inner = token[1:-1] if token.endswith('"') and len(token) > 1 else token[1:]
    return re.sub(r"\\(.)", r"\1", inner)


def fold_header(name: str, value: str, newline: str, limit: int = 78) -> str:
    """``Name: value`` folded at whitespace so that lines stay under ``limit``
    (whitespace runs collapse to one space)."""
    head = f"{name}:"
    lines: list[str] = []
    current = head
    for word in value.split():
        if current != head and len(current) + 1 + len(word) > limit:
            lines.append(current)
            current = " " + word
        else:
            current += " " + word
    lines.append(current)
    return newline.join(lines) + newline


# ---------------------------------------------------------------------------
# Parsing helpers
# ---------------------------------------------------------------------------


def parse_message(data: bytes) -> Message:
    return email.message_from_bytes(data, policy=compat32)


def message_bytes(message: Message) -> bytes:
    """Serialise a parsed (sub)message without refolding headers or mangling."""
    buffer = io.BytesIO()
    BytesGenerator(buffer, mangle_from_=False, maxheaderlen=0).flatten(message)
    return buffer.getvalue()


def detect_newline(data: bytes) -> str:
    head = data[:65536]
    return "\r\n" if head.count(b"\r\n") * 2 >= head.count(b"\n") and b"\r\n" in head else "\n"


def _param(part: Message, name: str, header: str = "content-type") -> str | None:
    value = part.get_param(name, header=header)
    if value is None:
        return None
    collapsed = collapse_rfc2231_value(value)
    return decode_header_value(str(collapsed))


def attachment_name(part: Message) -> str | None:
    raw = _param(part, "filename", "content-disposition") or _param(part, "name")
    if not raw:
        return None
    base = raw.replace("\\", "/").rstrip("/").split("/")[-1].strip()
    return base or None


def _disposition(part: Message) -> str:
    value = part.get("content-disposition")
    if not value:
        return ""
    return str(value).split(";", 1)[0].strip().lower()


def _is_attachment(part: Message) -> bool:
    return _disposition(part) == "attachment" or attachment_name(part) is not None


def _decode_text(part: Message) -> str:
    payload = part.get_payload(decode=True)
    data = payload if isinstance(payload, bytes) else b""
    codec = _codec(part.get_content_charset())
    if codec:
        try:
            return data.decode(codec)
        except UnicodeDecodeError:
            pass
    return decode_bytes(data)[0]


def _leaf_bytes(part: Message) -> bytes:
    if part.is_multipart():
        payload = part.get_payload()
        if isinstance(payload, list):
            return b"".join(message_bytes(p) for p in payload if isinstance(p, Message))
        return b""
    payload = part.get_payload(decode=True)
    return payload if isinstance(payload, bytes) else b""


def _header_id(path: str, index: int) -> str:
    return f"p{path}:{HEADER}{index}"


def _body_prefix(path: str) -> str:
    return f"p{path}:{BODY}"


UNIXFROM_ID = "unixfrom"


# ---------------------------------------------------------------------------
# Extraction
# ---------------------------------------------------------------------------


@dataclass(slots=True)
class _Extraction:
    document: Document
    ctx: ExtractionContext
    children: dict[str, str] = field(default_factory=dict)  # part path -> child id
    html_children: dict[str, dict[int, str]] = field(default_factory=dict)
    counter: int = 0


def extract_mime(data: bytes, document: Document, ctx: ExtractionContext) -> None:
    """Fill ``document`` with the segments and children of the MIME message ``data``."""
    message = parse_message(data)
    state = _Extraction(document, ctx)
    unixfrom = message.get_unixfrom()
    if unixfrom:
        document.segments.append(
            Segment(
                id=UNIXFROM_ID,
                text=_decode_raw(unixfrom[5:] if unixfrom.startswith("From ") else unixfrom),
                locator=(UNIXFROM_ID,),
                context=SegmentContext(SegmentKind.HEADER, label="From_"),
            )
        )
    _extract_part(message, "0", state)
    document.properties["mime_children"] = state.children
    document.properties["mime_html_children"] = state.html_children
    document.properties["newline"] = detect_newline(data)


def _extract_part(part: Message, path: str, state: _Extraction) -> None:
    document = state.document
    for index, (name, value) in enumerate(part.items()):
        lname = name.lower()
        if lname in DROPPED_HEADERS or lname in STRUCTURAL_HEADERS:
            continue
        text = decode_header_value(str(value))
        if not text.strip():
            continue
        document.segments.append(
            Segment(
                id=_header_id(path, index),
                text=text,
                locator=("header", path, index),
                context=SegmentContext(SegmentKind.HEADER, label=name[:60]),
            )
        )
    ctype = part.get_content_type()
    maintype = part.get_content_maintype()
    if ctype in _ENCRYPTED_TYPES or ctype == "multipart/encrypted":
        document.add_issue(
            Severity.ERROR,
            "mail.encrypted",
            "Message chiffré ou signé de façon opaque (S/MIME, PGP) : contenu illisible.",
        )
        return
    if ctype in _SIGNATURE_TYPES:
        document.add_issue(
            Severity.WARNING,
            "mail.signature_removed",
            "Signature électronique du message supprimée (elle ne serait plus valide).",
        )
        return
    if part.is_multipart() and maintype == "multipart":
        payload = part.get_payload()
        for i, sub in enumerate(payload if isinstance(payload, list) else []):
            state.ctx.check_cancelled()
            _extract_part(sub, f"{path}.{i}", state)
        return
    if maintype == "text" and not _is_attachment(part):
        text = _decode_text(part)
        prefix = _body_prefix(path)
        if part.get_content_subtype() == "html":
            source = HtmlSource(text)
            document.segments.extend(build_segments(source, prefix, "corps HTML : "))
            if source.data_uris:
                from anonyma.extractors.html import extract_data_uris

                state.html_children[path] = extract_data_uris(source, document, state.ctx)
        else:
            for i, (offset, chunk) in enumerate(chunk_text(text)):
                if not chunk.strip():
                    continue
                document.segments.append(
                    Segment(
                        id=f"{prefix}{i}",
                        text=chunk,
                        locator=("text", path, offset),
                        context=SegmentContext(SegmentKind.BODY, label="corps du message"),
                    )
                )
        return
    _extract_child(part, path, state)


def _extract_child(part: Message, path: str, state: _Extraction) -> None:
    ctype = part.get_content_type()
    state.counter += 1
    name = attachment_name(part)
    if ctype in ("message/rfc822", "message/global"):
        data = _leaf_bytes(part)
        name = name or f"message-joint-{state.counter}.eml"
    elif part.get_content_maintype() == "message":
        data = _leaf_bytes(part)
        name = name or f"rapport-{state.counter}.txt"
    else:
        data = _leaf_bytes(part)
        name = name or f"piece-jointe-{state.counter}{extension_for(ctype)}"
    state.ctx.check_cancelled()
    state.ctx.budget.consume(len(data), depth=state.ctx.depth + 1)
    child = state.ctx.extract_child(data, name, state.document)
    state.children[path] = child.id


