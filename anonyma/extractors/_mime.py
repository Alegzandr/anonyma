STRUCTURAL_HEADERS = frozenset({"content-type", "content-transfer-encoding", "content-disposition"})
#: Content-Type parameters kept on output (others, e.g. dates, are purged).
_KEPT_TYPE_PARAMS = ("format", "delsp", "reply-type", "method", "protocol", "micalg", "type")
