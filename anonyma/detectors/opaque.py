r"""Opaque technical identifiers (``Config.mask_opaque_ids``, every profile).

High-entropy tokens identify a document, a transaction or a person as surely as a
name: e-signature envelope ids, case references hashed into 40 hex characters,
session tokens in URLs, certificate fingerprints. Masked as ``IDENTIFIANT_TECHNIQUE``:

* UUIDs (``3f2b8c1e-...``), with or without braces;
* hexadecimal runs of at least 16 characters holding letters and digits (hashes,
  serial numbers), ``0x`` prefix allowed; colon/space separated byte pairs
  (certificate fingerprints, at least 8 pairs);
* base64 / base64url and other single tokens of at least 16 characters that look
  random (many letter/digit alternations, mixed case, few dictionary words);
* tokens of dash/underscore separated groups mixing case and digits
  (``TRX-a8F3k2-xyz-9Qm4Lp``, ``AB12-CD34-EF56-GH78``).

Ordinary words, numbers (prices, dates, phone numbers), IBANs and plates written as
usual, CSS colours, versions (``2.3.1``), product names (``iPhone15``, ``x64``) and
paths made of words are left alone. ``Config.opaque_id_whitelist`` lists values never
masked (exact, case-insensitive) or regular expressions prefixed ``re:``: a pattern
with an explicit anchor (``re:^CAS-``, ``re:-FR$``) is searched, any other one must
match the whole value (``re:FACT-\d{6}``). The list applies to every technical or
reference identifier (:class:`IdWhitelist`, also used by the regex detector and the
resolver).
"""

from __future__ import annotations

import math
from collections import Counter
from collections.abc import Sequence
from itertools import pairwise

import regex

from anonyma.config import Config
from anonyma.data import is_common_word
from anonyma.detectors._filters import skip_segment
from anonyma.logs import get_logger
from anonyma.models import Detector, Entity, EntityType, Profile, Segment
from anonyma.registry import register_detector

log = get_logger("detectors.opaque")

DETECTOR_NAME = "identifiants_techniques"
#: Below the verifier's certainty level: an identifier generated by a writer in an
#: output (a fresh XMP uuid) sends the file to review, never to quarantine. Values
#: of the batch left in an output are caught with certainty by the table check.
SCORE = 0.75

_EDGE_L = r"(?<![0-9A-Za-z_\-])"
_EDGE_R = r"(?![0-9A-Za-z_\-])"
_UUID = regex.compile(
    _EDGE_L
    + r"\{?[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}\}?"
    + _EDGE_R
)
_HEX = regex.compile(_EDGE_L + r"(?:0[xX])?[0-9A-Fa-f]{16,}" + _EDGE_R)
_HEX_PAIRS = regex.compile(
    r"(?<![0-9A-Za-z:])[0-9A-Fa-f]{2}(?P<sep>[: ])[0-9A-Fa-f]{2}(?:(?P=sep)[0-9A-Fa-f]{2}){6,}"
    r"(?![0-9A-Za-z:])"
)
#: Candidate tokens: letters, digits, dashes and underscores (base64url included).
_TOKEN = regex.compile(
    r"(?<![0-9A-Za-z_\-@])[A-Za-z0-9](?:[A-Za-z0-9_\-]*[A-Za-z0-9])?(?![0-9A-Za-z_\-@])"
)
#: Standard base64 (``+``, ``/``, ``=`` padding): checked as a whole.
_BASE64 = regex.compile(r"(?<![0-9A-Za-z+/=_\-@:.])[A-Za-z0-9+/]{20,}={0,2}(?![0-9A-Za-z+/=_\-@])")
_GROUP_SEP = regex.compile(r"[\-_]")
_LETTER_RUN = regex.compile(r"[A-Za-z]+")
_CHUNK = regex.compile(r"[A-Z]?[a-z]+|[A-Z]+(?![a-z])|\d+")
_DIGIT = regex.compile(r"\d")


def _alternations(text: str) -> int:
    """Letter/digit transitions (``a8F3`` -> 3, ``cv2024`` -> 1)."""
    kinds = [c.isdigit() for c in text if c.isalnum()]
    return sum(1 for a, b in pairwise(kinds) if a != b)


def _entropy(text: str) -> float:
    counts = Counter(text)
    n = len(text)
    return -sum(c / n * math.log2(c / n) for c in counts.values())


def _wordy(text: str) -> bool:
    """Mostly dictionary words (``ThisIsMyIdentifier``, ``Clients/Dupont/cv2024``)."""
    letters = sum(1 for c in text if c.isalpha())
    if not letters:
        return False
    covered = sum(
        len(chunk)
        for chunk in _CHUNK.findall(text)
        if chunk.isalpha() and len(chunk) >= 3 and is_common_word(chunk)
    )
    return covered * 2 >= letters


def _random_group(group: str) -> bool:
    """A group that looks generated: letters and digits interleaved (``a8F3k2``)."""
    return len(group) >= 4 and _alternations(group) >= 2


def _is_mixed(group: str) -> bool:
    return any(c.isdigit() for c in group) and any(c.isalpha() for c in group)


def looks_opaque(token: str) -> bool:
    """Whether a single token (no spaces) is a generated identifier."""
    core = token.rstrip("=")
    alnum = [c for c in core if c.isalnum()]
    digits = sum(1 for c in alnum if c.isdigit())
    letters = len(alnum) - digits
    if digits == 0 and len(alnum) < 20:
        return False
    if letters < 2:
        return False  # numbers, dates, phone numbers: other rules
    upper = any(c.isupper() for c in core)
    lower = any(c.islower() for c in core)
    groups = [g for g in _GROUP_SEP.split(core) if g]
    if len(groups) >= 2 and "/" not in core and "+" not in core:
        if len(alnum) < 10 or digits < 2:
            return False
        mixed = [g for g in groups if _is_mixed(g)]
        if any(_random_group(g) for g in mixed) and (
            (upper and lower) or sum(len(g) >= 4 for g in mixed) >= 2
        ):
            return not _wordy(core)
        return len([g for g in mixed if len(g) >= 3]) >= 3
    # A single run (base64 may hold + and /).
    if len(alnum) < 16:
        return False
    if _wordy(core):
        return False
    plain = "".join(alnum)
    if digits == 0:
        # Letters only (base64 of text): long, mixed case, capitals in runs.
        return (
            len(plain) >= 24
            and upper
            and lower
            and len(regex.findall(r"[A-Z]{2,}", plain)) >= 2
            and _entropy(plain) >= 3.8
        )
    if not (upper and lower) and not (upper and digits >= 4):
        return False  # lower-case + digits: hex rule, or words with numbers
    switches = _alternations(plain) + sum(
        1 for a, b in pairwise(plain) if a.isalpha() and b.isalpha() and a.isupper() != b.isupper()
    )
    return switches >= max(4, len(plain) // 5) and _entropy(plain) >= 3.0


class IdWhitelist:
    """``Config.opaque_id_whitelist``: exact values (case-insensitive) and ``re:``
    patterns (searched when anchored with ``^`` or ``$``, full match otherwise)."""

    def __init__(self, entries: Sequence[str]) -> None:
        self.exact: set[str] = set()
        self.patterns: list[tuple[regex.Pattern[str], bool]] = []
        for i, raw in enumerate(entries):
            entry = raw.strip()
            if not entry:
                continue
            if entry.startswith("re:"):
                source = entry[3:]
                anchored = source.startswith("^") or source.endswith("$")
                try:
                    self.patterns.append((regex.compile(source), anchored))
                except regex.error:
                    log.warning("invalid opaque id whitelist pattern #%d ignored", i)
            else:
                self.exact.add(entry.casefold())

    def allows(self, value: str) -> bool:
        value = value.strip()
        if value.casefold() in self.exact:
            return True
        return any(
            (p.search(value) if anchored else p.fullmatch(value)) for p, anchored in self.patterns
        )

    def __bool__(self) -> bool:
        return bool(self.exact or self.patterns)


@register_detector
class OpaqueIdDetector(Detector):
    name = DETECTOR_NAME
    min_profile = Profile.LIGHT

    @classmethod
    def is_enabled(cls, config: Config) -> bool:
        return config.mask_opaque_ids

    def __init__(self, config: Config) -> None:
        super().__init__(config)
        self.active = config.mask_opaque_ids
        self.whitelist = IdWhitelist(config.opaque_id_whitelist or [])

    def detect(self, segments: Sequence[Segment], document_id: str) -> list[Entity]:
        if not self.active:
            return []
        found: list[Entity] = []
        for segment in segments:
            text = segment.text
            if len(text) < 10 or skip_segment(segment):
                continue
            for start, end, rule in self._spans(text):
                value = text[start:end]
                if self.whitelist.allows(value):
                    continue
                found.append(
                    Entity(
                        entity_type=EntityType.OPAQUE_ID,
                        value=value,
                        document_id=document_id,
                        segment_id=segment.id,
                        start=start,
                        end=end,
                        score=SCORE,
                        detector=self.name,
                        attributes={"rule": rule},
                    )
                )
        return found

    @staticmethod
    def _spans(text: str) -> list[tuple[int, int, str]]:
        return opaque_spans(text)


def opaque_spans(text: str) -> list[tuple[int, int, str]]:
    """``(start, end, rule)`` of every opaque identifier of ``text``, whether or not
    they are masked: :mod:`anonyma.atomic` keeps them whole."""
    spans: list[tuple[int, int, str]] = []

    def free(start: int, end: int) -> bool:
        return not any(s < end and start < e for s, e, _ in spans)

    for m in _UUID.finditer(text):
        spans.append((m.start(), m.end(), "uuid"))
    for m in _HEX.finditer(text):
        value = m.group().removeprefix("0x").removeprefix("0X")
        digits = sum(c.isdigit() for c in value)
        if digits >= 2 and len(value) - digits >= 2 and free(m.start(), m.end()):
            spans.append((m.start(), m.end(), "hexadecimal"))
    for m in _HEX_PAIRS.finditer(text):
        pairs = m.group().split(m.group("sep"))
        with_letter = sum(any(c.isalpha() for c in p) for p in pairs)
        if m.group("sep") == " " and with_letter * 4 < len(pairs):
            continue  # spaced digit pairs: phone or account numbers
        if free(m.start(), m.end()):
            spans.append((m.start(), m.end(), "empreinte"))
    for m in _BASE64.finditer(text):
        token = m.group()
        if not any(c in token for c in "+/="):
            continue  # plain tokens: next rule
        parts = [p for p in regex.split(r"[+/]", token.rstrip("=")) if p]
        if any(len(p) >= 3 and p.isalpha() and is_common_word(p) for p in parts):
            continue  # a path or an expression made of words
        if free(m.start(), m.end()) and looks_opaque(token):
            spans.append((m.start(), m.end(), "base64"))
    for m in _TOKEN.finditer(text):
        token = m.group()
        # looks_opaque needs 10 alphanumerics, and 20 without a digit: skip words.
        if len(token) < 10 or (len(token) < 20 and not _DIGIT.search(token)):
            continue
        if free(m.start(), m.end()) and looks_opaque(token):
            spans.append((m.start(), m.end(), "jeton"))
    return [s for s in spans if not _software_build(text, s[0])]


#: Build ids of office suites in generator strings (``LibreOffice/24.2.7.2$Windows_X86_64
#: LibreOffice_project/<40 hex>``): they identify the software, not the document, and
#: LibreOffice stamps them again on every file it saves (legacy doc/xls/ppt outputs).
_BUILD_PREFIX = regex.compile(r"_project/$")


def _software_build(text: str, start: int) -> bool:
    return bool(_BUILD_PREFIX.search(text[max(0, start - 10) : start]))


